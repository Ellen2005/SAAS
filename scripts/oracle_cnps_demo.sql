DECLARE
    v_contrib_date DATE;
    v_due_date DATE;
    v_amount NUMBER(15,2);
    v_status VARCHAR2(20);
    v_method VARCHAR2(30);
    v_ssn VARCHAR2(50);
    v_name VARCHAR2(200);
    v_late_fee NUMBER(15,2);
    v_emp_id NUMBER;
    v_reg VARCHAR2(10);
    v_emp_count NUMBER;
    CURSOR emp_cursor IS SELECT employer_id, regional_code, employee_count FROM employers WHERE employee_count > 0;
BEGIN
    FOR emp_rec IN emp_cursor LOOP
        v_emp_id := emp_rec.employer_id;
        v_reg := emp_rec.regional_code;
        v_emp_count := emp_rec.employee_count;
        IF v_emp_count IS NULL OR v_emp_count <= 0 THEN
            v_emp_count := 10;
        END IF;

        FOR month_offset IN 0..11 LOOP
            FOR c IN 1..TRUNC(DBMS_RANDOM.VALUE(1, LEAST(v_emp_count, 50) + 1)) LOOP
                v_contrib_date := ADD_MONTHS(SYSDATE, -month_offset) - TRUNC(DBMS_RANDOM.VALUE(0,29));
                v_due_date := v_contrib_date + 30;

                -- 15% payment issues
                IF DBMS_RANDOM.VALUE < 0.15 THEN
                    v_status := CASE TRUNC(DBMS_RANDOM.VALUE(1,4))
                        WHEN 1 THEN 'overdue' WHEN 2 THEN 'rejected' ELSE 'partial' END;
                    IF v_status = 'overdue' THEN
                        v_late_fee := GREATEST(0, (SYSDATE - v_due_date) * 500);
                    ELSE
                        v_late_fee := 0;
                    END IF;
                ELSE
                    v_status := 'paid';
                    v_late_fee := 0;
                END IF;

                -- Amount anomalies
                IF DBMS_RANDOM.VALUE < 0.05 THEN
                    v_amount := CASE TRUNC(DBMS_RANDOM.VALUE(1,5))
                        WHEN 1 THEN 0 WHEN 2 THEN -1000 WHEN 3 THEN 999999 ELSE NULL END;
                ELSIF v_reg = 'YAO' AND DBMS_RANDOM.VALUE < 0.3 THEN
                    v_amount := ROUND(DBMS_RANDOM.VALUE(25000,45000), 2);
                ELSIF v_reg IN ('KRI','EVD') AND DBMS_RANDOM.VALUE < 0.4 THEN
                    v_amount := ROUND(DBMS_RANDOM.VALUE(5000,15000), 2);
                ELSE
                    v_amount := ROUND(DBMS_RANDOM.VALUE(15000,25000), 2);
                END IF;

                -- 2% missing SSN
                IF DBMS_RANDOM.VALUE < 0.02 THEN
                    v_ssn := NULL;
                    v_name := 'Unknown Employee ' || TO_CHAR(c);
                ELSE
                    v_ssn := 'SSN' || TO_CHAR(v_emp_id) || LPAD(TO_CHAR(c), 3, '0');
                    v_name := 'Employee ' || TO_CHAR(c) || ' - Emp ' || TO_CHAR(v_emp_id);
                END IF;

                v_method := CASE TRUNC(DBMS_RANDOM.VALUE(1,5))
                    WHEN 1 THEN 'bank_transfer' WHEN 2 THEN 'cash'
                    WHEN 3 THEN 'check' WHEN 4 THEN 'mobile_money' ELSE 'bank_transfer' END;

                INSERT INTO contributions (employer_id, employee_ssn, employee_name,
                    contribution_amount, contribution_date, due_date, payment_status,
                    regional_code, payment_method, late_fee)
                VALUES (v_emp_id, v_ssn, v_name, v_amount, v_contrib_date, v_due_date,
                    v_status, v_reg, v_method, v_late_fee);
            END LOOP;
        END LOOP;
    END LOOP;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Contributions inserted.');
END;
