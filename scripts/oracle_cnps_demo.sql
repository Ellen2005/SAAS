-- 1. REGIONAL OFFICES
CREATE TABLE regional_offices (
    office_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR2(10) NOT NULL UNIQUE,
    name            VARCHAR2(100) NOT NULL,
    region          VARCHAR2(50),
    manager_name    VARCHAR2(100),
    staff_count     NUMBER DEFAULT 0,
    budget_allocated NUMBER(15,2) DEFAULT 0,
    created_at      DATE DEFAULT SYSDATE
);

-- 2. EMPLOYERS
CREATE TABLE employers (
    employer_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_code       VARCHAR2(20) NOT NULL UNIQUE,
    company_name        VARCHAR2(200),
    sector              VARCHAR2(100),
    employee_count      NUMBER,
    regional_code       VARCHAR2(10) REFERENCES regional_offices(code),
    registration_date   DATE,
    status              VARCHAR2(20) DEFAULT 'active',
    last_payment_date   DATE
);

-- 3. CONTRIBUTIONS (main transactional table)
CREATE TABLE contributions (
    contribution_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id         NUMBER NOT NULL REFERENCES employers(employer_id),
    employee_ssn        VARCHAR2(50),
    employee_name       VARCHAR2(200),
    contribution_amount NUMBER(15,2),
    contribution_date   DATE NOT NULL,
    due_date            DATE,
    payment_status      VARCHAR2(20) DEFAULT 'paid',
    regional_code       VARCHAR2(10) REFERENCES regional_offices(code),
    payment_method      VARCHAR2(30),
    late_fee            NUMBER(15,2) DEFAULT 0,
    created_at          DATE DEFAULT SYSDATE
);

-- 4. PENSION PAYMENTS
CREATE TABLE pension_payments (
    payment_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_ssn     VARCHAR2(50),
    beneficiary_name    VARCHAR2(200),
    pension_amount      NUMBER(15,2),
    payment_date        DATE NOT NULL,
    payment_status      VARCHAR2(20) DEFAULT 'paid',
    regional_code       VARCHAR2(10) REFERENCES regional_offices(code),
    processing_days     NUMBER DEFAULT 0,
    rejection_reason    VARCHAR2(500),
    created_at          DATE DEFAULT SYSDATE
);

-- 5. WORKPLACE ACCIDENTS (AT/MP Claims)
CREATE TABLE workplace_accidents (
    accident_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_ssn        VARCHAR2(50),
    employee_name       VARCHAR2(200),
    employer_id         NUMBER NOT NULL REFERENCES employers(employer_id),
    accident_date       DATE NOT NULL,
    accident_type       VARCHAR2(50),
    severity            VARCHAR2(20),
    claim_amount        NUMBER(15,2),
    claim_status        VARCHAR2(30) DEFAULT 'pending',
    regional_code       VARCHAR2(10) REFERENCES regional_offices(code),
    processing_days     NUMBER DEFAULT 0,
    rejection_reason    VARCHAR2(500),
    created_at          DATE DEFAULT SYSDATE
);

-- Indexes for performance
CREATE INDEX idx_contrib_region ON contributions(regional_code);
CREATE INDEX idx_contrib_status ON contributions(payment_status);
CREATE INDEX idx_contrib_date ON contributions(contribution_date);
CREATE INDEX idx_contrib_employer ON contributions(employer_id);
CREATE INDEX idx_pension_region ON pension_payments(regional_code);
CREATE INDEX idx_pension_status ON pension_payments(payment_status);
CREATE INDEX idx_accident_region ON workplace_accidents(regional_code);
CREATE INDEX idx_accident_status ON workplace_accidents(claim_status);

