SELECT regional_code, COUNT(*) AS total,
       SUM(CASE WHEN claim_status = 'rejected' THEN 1 ELSE 0 END) AS rejected,
       ROUND(100 * SUM(CASE WHEN claim_status = 'rejected' THEN 1 ELSE 0 END) / COUNT(*), 1) AS reject_pct
FROM workplace_accidents GROUP BY regional_code ORDER BY reject_pct DESC;

