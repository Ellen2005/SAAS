// Hook for using translations
export function useLang() {
  const [lang, setLang] = useState('fr'); // Default to French for CNPS
  
  const t = (key) => {
    return translations[lang]?.[key] || translations['en'][key] || key;
  };
  
  return { lang, setLang, t };
}